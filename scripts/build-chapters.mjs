#!/usr/bin/env node
/**
 * Assembles docs/CHAPTER4_DRAFT.md from docs/chapters/chapter4.template.md, replacing each
 * {{T-ID}} marker with the matching table generated from the campaign data by
 * scripts/results-tables.mjs. Fails if a marker has no table, so no table can be left out.
 * Usage: node scripts/build-chapters.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const latest = (prefix) => {
  const dirs = fs
    .readdirSync(path.join(root, 'docs/results'))
    .filter((d) => d.startsWith(prefix))
    .sort();
  if (!dirs.length) throw new Error(`No ${prefix}* directory in docs/results`);
  return path.join(root, 'docs/results', dirs.at(-1));
};
const tables = execFileSync(
  'node',
  [
    path.join(root, 'scripts/results-tables.mjs'),
    latest('campaign-'),
    latest('ablation-'),
    '--start=7',
  ],
  { encoding: 'utf8' },
);
fs.writeFileSync(path.join(root, 'docs/results/chapter4-tables.md'), tables);
const blocks = {};
for (const part of tables
  .split(/^<!-- (T-[A-Z]+) -->$/m)
  .slice(1)
  .reduce((acc, x, i, arr) => (i % 2 ? acc : [...acc, [x, arr[i + 1]]]), []))
  blocks[part[0]] = part[1].trim();
const template = fs.readFileSync(path.join(root, 'docs/chapters/chapter4.template.md'), 'utf8');
const doc = template.replace(/\{\{(T-[A-Z]+)\}\}/g, (_, id) => {
  if (!blocks[id]) throw new Error(`Missing generated table ${id}`);
  return blocks[id];
});
fs.writeFileSync(
  path.join(root, 'docs/CHAPTER4_DRAFT.md'),
  `<!-- Generated by scripts/build-chapters.mjs from docs/chapters/chapter4.template.md and ${path.relative(root, latest('campaign-'))}. Do not edit tables by hand. -->\n\n${doc}`,
);
console.log('wrote docs/CHAPTER4_DRAFT.md with', Object.keys(blocks).length, 'generated tables');
